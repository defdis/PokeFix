/**
 * Bundles exactly the icons referenced in src/ into src/renderer/icons-generated.ts,
 * so the renderer never fetches api.iconify.design at runtime (CSP: default-src 'self').
 * Re-run after adding a new <Icon icon="prefix:name" /> usage:
 *   node .erb/scripts/generate-icons.js
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'src');
const OUT = path.join(SRC, 'renderer', 'icons-generated.ts');
const EXTRA = ['ic:baseline-star']; // referenced dynamically (template literal suffix)
const PREFIXES = new Set([
  'bx',
  'carbon',
  'ei',
  'fluent',
  'heroicons',
  'ic',
  'iconoir',
  'line-md',
  'lucide',
  'mdi',
  'tdesign',
  'uil',
]);
const ICON_RE = /['"`]([a-z][a-z0-9-]*):([a-z0-9-]+)['"`]/g;

function collectUsed() {
  const used = new Set(EXTRA);
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      if (!/\.(tsx?|jsx?|css|html)$/.test(entry.name)) continue;
      const text = fs.readFileSync(full, 'utf8');
      let m;
      while ((m = ICON_RE.exec(text))) {
        if (PREFIXES.has(m[1])) used.add(`${m[1]}:${m[2]}`);
      }
    }
  };
  walk(SRC);
  return used;
}

const used = collectUsed();
const byPrefix = new Map();
for (const key of used) {
  const [prefix, name] = key.split(':');
  if (!byPrefix.has(prefix)) byPrefix.set(prefix, new Set());
  byPrefix.get(prefix).add(name);
}

const payload = {};
for (const [prefix, names] of [...byPrefix.entries()].sort()) {
  const pkgPath = require.resolve(`@iconify-json/${prefix}/icons.json`);
  const data = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const icons = {};
  const aliases = {};
  const addWithDeps = (name, depth) => {
    if (icons[name] || aliases[name]) return;
    if (data.icons[name]) {
      icons[name] = data.icons[name];
      return;
    }
    const alias = data.aliases && data.aliases[name];
    if (!alias) {
      console.warn(`WARN: icon not found: ${prefix}:${name}`);
      return;
    }
    aliases[name] = alias;
    if (depth < 4) addWithDeps(alias.parent, depth + 1);
  };
  for (const n of [...names].sort()) addWithDeps(n, 0);
  payload[prefix] = {
    prefix,
    icons,
    ...(Object.keys(aliases).length ? {aliases} : {}),
    ...(data.width ? {width: data.width, height: data.height} : {}),
  };
}

const body = Object.entries(payload)
  .map(([, col]) => `addCollection(${JSON.stringify(col)});`)
  .join('\n');

const out = `// GENERATED by .erb/scripts/generate-icons.js — do not edit by hand.
// Bundles only the icons referenced in src/ so the app never hits api.iconify.design at runtime.
/* eslint-disable */
import { addCollection } from '@iconify/react';

${body}
`;
fs.writeFileSync(OUT, out);
console.log(
  `wrote ${OUT}: ${Object.values(payload).reduce((n, c) => n + Object.keys(c.icons).length + Object.keys(c.aliases ?? {}).length, 0)} icons across ${Object.keys(payload).length} collections`
);
